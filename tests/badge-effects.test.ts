test('shine uses a duplicate alpha image and a clipped scan instead of a rectangle mask', () => {
  const component = read('components/UserDisplayName.tsx')
  const css = read('app/globals.css')
  assert.match(component, /className="badge-shimmer-clip"/)
  assert.match(component, /<img src=\{badge\.imageUrl \|\| ''\} alt="" className="badge-shimmer-layer" \/>/)
  assert.match(component, /className="user-badge-image"/)
  assert.equal((component.match(/className="user-badge-image"/g) || []).length, 1)
  assert.doesNotMatch(component, /badge-shine-mask/)
  assert.match(css, /\.badge-shimmer-clip \{[\s\S]*overflow:hidden[\s\S]*opacity:0/)
  assert.match(css, /@supports \(clip-path:polygon\(0 0,100% 0,100% 100%,0 100%\)\)[\s\S]*\.badge-effect-shine \.badge-shimmer-clip \{[\s\S]*opacity:1/)
  assert.match(css, /\.badge-shimmer-layer \{[\s\S]*clip-path:polygon\([\s\S]*filter:brightness\([\s\S]*drop-shadow[\s\S]*transform:translate3d\(-140%,0,0\)/)
  assert.doesNotMatch(css, /\.badge-shimmer-layer \{[^}]*background(?:-color)?:/)
  assert.doesNotMatch(css, /\.badge-shimmer-clip \{[^}]*background(?:-color)?:/)
  assert.doesNotMatch(css, /\.badge-shimmer-clip \{[^}]*border(?:-\w+)?:/)
  assert.doesNotMatch(css, /\.badge-shimmer-clip \{[^}]*box-shadow:/)
  assert.doesNotMatch(css, /badge-shine-mask|mask-image:var\(--badge-shine-mask\)/)
  assert.match(css, /\.badge-visual \{[\s\S]*border:0[\s\S]*background:transparent[\s\S]*box-shadow:none/)
  assert.match(css, /@keyframes eason-badge-shine[\s\S]*transform:translate3d\(-140%,0,0\)/)
  assert.match(css, /@keyframes eason-badge-shine-fallback[\s\S]*filter:drop-shadow/)
  assert.match(css, /animation:eason-badge-shine 4s linear infinite; animation-play-state:running/)
  assert.match(css, /\.badge-effect-glow \.user-badge-image[\s\S]*animation:eason-badge-glow/)
  assert.match(css, /filter:drop-shadow/)
  assert.doesNotMatch(css, /@property[^}]*badge-shine/)
  assert.doesNotMatch(component, /<img[^>]+badge-visual-shine/)
})

