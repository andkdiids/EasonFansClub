test('nickname shine keeps an inherited base layer and a separate narrow color overlay', () => {
  const component = read('components/UserDisplayName.tsx')
  const css = read('app/globals.css')
  const nicknameCss = css.slice(css.indexOf('/* E院勋章'), css.indexOf('.user-display-badge {'))
  assert.match(component, /isBadgeNicknameShineEnabled/)
  assert.match(component, /getBadgeNicknameShineColor/)
  assert.match(component, /className="user-display-name-base"/)
  assert.match(component, /className="user-display-name-highlight" aria-hidden="true"/)
  assert.match(component, /nicknameShineEnabled \?/)
  assert.match(nicknameCss, /\.user-display-name-shine \{[^}]*color:inherit/)
  assert.match(nicknameCss, /\.user-display-name-base \{ color:inherit; \}/)
  assert.match(nicknameCss, /\.user-display-name-highlight \{[^}]*color:var\(--badge-shine-color/)
  assert.match(nicknameCss, /-webkit-mask-image:linear-gradient/)
  assert.match(nicknameCss, /-webkit-mask-size:260% 100%; mask-size:260% 100%/)
  assert.match(nicknameCss, /animation:eason-badge-nickname-shine 2s ease-in-out infinite normal/)
  assert.doesNotMatch(nicknameCss, /alternate(?:-reverse)?/)
  const keyframeStart = css.indexOf('@keyframes eason-badge-nickname-shine')
  const nicknameKeyframes = css.slice(keyframeStart, css.indexOf('\n', keyframeStart))
  assert.match(nicknameKeyframes, /0%[^}]*mask-position:100% 0/)
  assert.match(nicknameKeyframes, /100%[^}]*mask-position:0 0/)
  assert.doesNotMatch(nicknameKeyframes, /mask-position:0 0[^}]*mask-position:100% 0/)
  assert.doesNotMatch(component, /nicknameEffectClass|user-display-name-text-gradient/)
  assert.doesNotMatch(nicknameCss, /background-clip:text|-webkit-text-fill-color|text-shadow/)
})

